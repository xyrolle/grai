// Writes src/plural-rules.ts: CLDR's cardinal plural rules, by language, from the cldr-core
// package this repo pins as a dev dependency. The compiler compiles the rules of a project's
// locales into its output, so no plural data is read at run time.
//
// usage: node scripts/plural-rules.ts
import { readFileSync, writeFileSync } from "node:fs";

const cldr = new URL("../node_modules/cldr-core/", import.meta.url);
const { version } = JSON.parse(
	readFileSync(new URL("package.json", cldr), "utf8"),
);
const license = readFileSync(new URL("LICENSE", cldr), "utf8").trim();
const plurals = JSON.parse(
	readFileSync(new URL("supplemental/plurals.json", cldr), "utf8"),
);
const cardinal: Record<string, Record<string, string>> = plurals.supplemental[
	"plurals-type-cardinal"
];

const rules: Record<string, Record<string, string>> = {};
for (const [language, categories] of Object.entries(cardinal)) {
	const conditions: Record<string, string> = {};
	for (const [name, rule] of Object.entries(categories)) {
		const category = name.replace("pluralRule-count-", "");
		const condition = rule.split("@")[0]?.trim() ?? "";
		if (category !== "other") conditions[category] = condition;
	}
	rules[language] = conditions;
}

writeFileSync(
	new URL("../src/plural-rules.ts", import.meta.url),
	`// Generated by scripts/plural-rules.ts from CLDR's cardinal plural rules, cldr-core ${version},
// without their samples. Do not edit.
//
${license
	.split("\n")
	.map((line) => `// ${line}`.trimEnd())
	.join("\n")}

/** Each language's cardinal plural rules: each category's condition, but other's, which is the rest. */
export const pluralRules: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(rules, null, "\t")};
`,
);
